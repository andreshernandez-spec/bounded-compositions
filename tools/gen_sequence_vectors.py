#!/usr/bin/env python3
"""Generate tests/data/sequence_vectors.inc from the Python bindings.

Each row is the rank of point `index` of one sequence. The C++ test
(tests/test_sequence_vectors.cpp) builds the same spaces and sequences in C++
and checks every row, so the bindings and the library must agree point for
point, seeds of 64 bits included; python/tests/test_vectors.py checks the
bindings against the same file.

Usage: gen_sequence_vectors.py <repository root>
"""

import pathlib
import sys


def spaces(bc):
    """The spaces by id; tests/test_sequence_vectors.cpp builds the same."""
    return {
        0: bc.Space(100, [0] * 100, [100] * 100),
        1: bc.Space(5, [-3, 0, -1, 0, -2, 0, 0, -1], [4, 6, 3, 5, 2, 7, 4, 3]),
        2: bc.Space(40, [0] * 12, [10] * 12, min_count=3, max_count=8, min_size=[2] * 12,
                    groups=[bc.Group([0, 1, 2], min_sum=5, max_sum=15),
                            bc.Group(list(range(6, 12)), min_sum=10, max_sum=30),
                            bc.Group([2, 3, 8], max_sum=12)]),
    }


PREFIXES = {0: [3], 1: [1], 2: [2]}
SEEDS = {
    "rank": [None, 1, 2**63, 2**64 - 1],
    "scaled_rank": [None],
    "iid": [0, 12345, 2**64 - 1],
    "coordinate": [None, 9, 2**64 - 1],
}
INDICES = [0, 1, 2, 3, 7, 100, 1000, 65537]


def make(bc, s, kind, seed, region):
    if kind == "rank":
        return bc.rank_sequence(s, region, seed=seed)
    if kind == "scaled_rank":
        return bc.scaled_rank_sequence(s)
    if kind == "iid":
        return bc.iid_sequence(s, seed, region)
    return bc.coordinate_sequence(s, region, seed=seed)


def rows(bc):
    out = []
    for sid, s in spaces(bc).items():
        for kind, seeds in SEEDS.items():
            for seed in seeds:
                for prefix in ([], PREFIXES[sid]):
                    if prefix and kind == "scaled_rank":
                        continue
                    region = bc.subtree(s, prefix) if prefix else None
                    q = make(bc, s, kind, seed, region)
                    for i in INDICES:
                        if i < q.capacity:
                            out.append((sid, kind, seed, prefix, i, q.rank_at(i)))
    return out


def format_row(sid, kind, seed, prefix, i, rank):
    has_seed = seed is not None
    pre = ", ".join(str(v) for v in prefix)
    return (f'{{{sid}, "{kind}", {seed if has_seed else 0}u, {str(has_seed).lower()}, '
            f'{len(prefix)}, {{{pre}}}, {i}u, "{rank}"}},')


def main():
    if len(sys.argv) != 2:
        print((__doc__ or "").strip())
        return 2
    import bounded_compositions as bc

    root = pathlib.Path(sys.argv[1])
    lines = ["// Generated by tools/gen_sequence_vectors.py from the Python bindings. Do not edit.",
             "// space id, kind, seed, has seed, prefix length, prefix, point index, rank"]
    lines += [format_row(*r) for r in rows(bc)]
    (root / "tests" / "data" / "sequence_vectors.inc").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 2} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())

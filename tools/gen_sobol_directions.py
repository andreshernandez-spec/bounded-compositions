def wrap(values, per_line=24):
    items = [str(v) for v in values]
    return ",\n".join("    " + ", ".join(items[i:i + per_line])
                      for i in range(0, len(items), per_line))


def main():
    if len(sys.argv) != 3:
        print((__doc__ or "").strip())
        return 2
    source = pathlib.Path(sys.argv[1])
    data = source.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED_SHA256:
        print(f"unexpected SHA-256 {digest} for {source}")
        return 1
    degree, coeffs, offset, initial = [], [], [0], []
    lines = data.decode("ascii").splitlines()
    for expected_dim, line in enumerate(lines[1:], start=2):
        fields = [int(v) for v in line.split()]
        d, s, a, m = fields[0], fields[1], fields[2], fields[3:]
        if d != expected_dim or len(m) != s:
            raise ValueError(f"malformed line for dimension {expected_dim}: {line!r}")
        degree.append(s)
        coeffs.append(a)
        initial.extend(m)
        offset.append(len(initial))
    dims = len(degree) + 1
    comment = "\n".join(("// " + l).rstrip() for l in LICENCE.splitlines())
    out = f"""// Generated by tools/gen_sobol_directions.py. Do not edit.
//
{comment}

#include "sobol_directions.hpp"

namespace bounded_compositions {{
namespace detail {{

const int sobol_max_dims = {dims};

// Dimension d (2..{dims}) is entry d - 2: the degree s and coefficient bits a
// of its primitive polynomial, and its s initial direction numbers m_1..m_s,
// which are sobol_initial[sobol_offset[d - 2] .. sobol_offset[d - 1]).
const unsigned char sobol_degree[{len(degree)}] = {{
{wrap(degree, 40)}
}};

const std::uint32_t sobol_coeffs[{len(coeffs)}] = {{
{wrap(coeffs, 16)}
}};

const std::uint32_t sobol_offset[{len(offset)}] = {{
{wrap(offset, 16)}
}};

const std::uint32_t sobol_initial[{len(initial)}] = {{
{wrap(initial, 20)}
}};

}}  // namespace detail
}}  // namespace bounded_compositions
"""
    root = pathlib.Path(sys.argv[2])
    (root / "src" / "sobol_directions.cpp").write_text(out)
    print(f"{dims} dimensions, {len(initial)} initial direction numbers")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Generate reference values for the C++ tests from Python's big integers.

Writes tests/data/natural_vectors.inc, tests/data/space_sizes.inc,
tests/data/philox_vectors.inc and tests/data/sobol_vectors.inc. The seed is
fixed, so rerunning gives the same files. The Philox vectors need numpy and the
Sobol vectors scipy.

Usage: gen_test_vectors.py <repository root>
"""

import math
import pathlib
import random
import sys

SEED = 20261002


def natural_vectors(rng):
    edges = [0, 1, 2, 2**32 - 1, 2**32, 2**63, 2**64 - 1, 2**64, 2**64 + 1,
             2**128 - 1, 2**128, 2**192 + 12345]
    values = list(edges)
    for bits in (1, 8, 31, 32, 33, 63, 64, 65, 100, 127, 128, 129, 200, 256, 511, 512, 1000, 3000):
        for _ in range(2):
            values.append(rng.getrandbits(bits) | (1 << (bits - 1)))
    rows = []
    for _ in range(150):
        a = rng.choice(values)
        b = rng.choice(values)
        m = rng.choice([0, 1, 7, 10, 1_000_000_000, 2**32 - 1, rng.getrandbits(32)])
        d = rng.choice([1, 2, 10, 1_000_000_000, 2**32 - 1, rng.getrandbits(32) | 1])
        rows.append((a, b, m, d))
    out = ["// Generated by tools/gen_test_vectors.py. Do not edit.",
           "// a, b, a + b, a - b (empty if negative), sign of a - b, m, a * m, d, a / d, a % d"]
    for a, b, m, d in rows:
        diff = str(a - b) if a >= b else ""
        cmp = (a > b) - (a < b)
        out.append(f'{{"{a}", "{b}", "{a + b}", "{diff}", {cmp}, {m}u, "{a * m}", {d}u, '
                   f'"{a // d}", {a % d}u}},')
    return "\n".join(out) + "\n"


def bounded_count(n, total, lo, hi):
    """Compositions of total into n parts, each in [lo, hi], by inclusion-exclusion."""
    t = total - n * lo
    cap = hi - lo
    if t < 0 or cap < 0:
        return 0
    count = 0
    for j in range(n + 1):
        top = t - j * (cap + 1)
        if top < 0:
            break
        count += (-1) ** j * math.comb(n, j) * math.comb(top + n - 1, n - 1)
    return count


def space_sizes():
    cases = [
        (1, 5, 0, 10), (1, 5, 6, 10), (2, 10, 0, 10), (3, 7, 0, 7),
        (5, 12, 0, 4), (5, 12, -3, 6), (10, 0, -2, 2), (10, -5, -2, 2),
        (4, 100, 0, 100), (20, 100, 0, 100), (20, 100, 0, 7), (20, 100, 3, 8),
        (100, 100, 0, 100), (100, 100, 0, 3), (60, 600, -10, 40),
        (300, 300, 0, 300), (200, 1000, 0, 10), (7, 30, 5, 5), (7, 35, 5, 5),
    ]
    out = ["// Generated by tools/gen_test_vectors.py. Do not edit.",
           "// parts, total, lower (every part), upper (every part), exact size"]
    for n, total, lo, hi in cases:
        out.append(f'{{{n}, {total}, {lo}, {hi}, "{bounded_count(n, total, lo, hi)}"}},')
    return "\n".join(out) + "\n"


def philox_vectors(rng):
    """Philox4x64-10 blocks from numpy, whose generator increments the counter
    before each block: the block for counter c is the first block after c - 1."""
    from numpy.random import Philox
    mask = (1 << 64) - 1
    cases = [(0, 0), ((1 << 256) - 1, (1 << 128) - 1)]
    cases += [(rng.getrandbits(256), rng.getrandbits(128)) for _ in range(30)]
    cases += [(rng.getrandbits(20), rng.getrandbits(64)) for _ in range(10)]
    out = ["// Generated by tools/gen_test_vectors.py from numpy.random.Philox. Do not edit.",
           "// counter[4], key[2], block[4]"]
    for counter, key in cases:
        block = Philox(counter=(counter - 1) % (1 << 256), key=key).random_raw(4)
        c = [(counter >> (64 * i)) & mask for i in range(4)]
        k = [(key >> (64 * i)) & mask for i in range(2)]
        def group(values):
            return "{" + ", ".join(f"0x{v:016x}u" for v in values) + "}"
        out.append(f"{{{group(c)}, {group(k)}, {group(int(b) for b in block)}}},")
    return "\n".join(out) + "\n"


def sobol_vectors():
    """Unscrambled Sobol points from scipy, 30 bits, for a spread of dimensions
    (0-based) including the last ones, at the first 64 indices and far out."""
    import numpy as np
    from scipy.stats import qmc
    dims = list(range(16)) + [100, 101, 102, 103, 1000, 5000, 12345] + list(range(21190, 21201))
    first = qmc.Sobol(d=21201, scramble=False, bits=30).random(64)
    far_engine = qmc.Sobol(d=21201, scramble=False, bits=30)
    far_start = 1_000_003
    far_engine.fast_forward(far_start)
    far = far_engine.random(2)
    out = ["// Generated by tools/gen_test_vectors.py from scipy.stats.qmc.Sobol"
           "(scramble=False, bits=30). Do not edit.",
           "// dimension (0-based), point index, top 30 bits of the coordinate"]
    for d in dims:
        for i in range(64):
            out.append(f"{{{d}, {i}u, {int(np.ldexp(first[i, d], 30))}u}},")
        for j in range(2):
            out.append(f"{{{d}, {far_start + j}u, {int(np.ldexp(far[j, d], 30))}u}},")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 2:
        print(__doc__.strip())
        return 2
    data = pathlib.Path(sys.argv[1]) / "tests" / "data"
    data.mkdir(parents=True, exist_ok=True)
    rng = random.Random(SEED)
    (data / "natural_vectors.inc").write_text(natural_vectors(rng))
    (data / "space_sizes.inc").write_text(space_sizes())
    (data / "philox_vectors.inc").write_text(philox_vectors(rng))
    (data / "sobol_vectors.inc").write_text(sobol_vectors())
    return 0


if __name__ == "__main__":
    sys.exit(main())
